#!/usr/bin/env python3
"""
layout_asserts.py - QA gate 2: static_assert(sizeof / offsetof) for every PDB class.

Reads reference/manifest/pdb/<dll>.types.json (tools/pdb_types.py, live generation
of every UDT) and writes source/missions/shared/vsr_layout_asserts.h. Each
generated class header ends with

    #define VSR_LAYOUT_CHECK_<Tag>
    #include "vsr_layout_asserts.h"

and this header, under that guard, defines `struct VsrLayoutCheck_<Tag>` whose
static member function holds the static_asserts (MSVC enforces access in
offsetof, so the class befriends that struct - one line, no layout effect).

Only members declared directly in a class are asserted (TPI members are
per-class; base members are asserted in the base). Nested types get their own
block, triggered by the outer class's guard.

Usage: python tools/layout_asserts.py [--out source/missions/shared/vsr_layout_asserts.h]
stdlib only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# Classes whose declarations the scaffold generates (SDK / CRT / Lua types excluded).
SKIP_PREFIX = ("std::", "_", "$", "<", "tag", "type_info", "localeinfo", "lconv", "tm", "__",
               "HINSTANCE", "I", "H", "APP", "ASSOC", "CPVIEW", "DEFAULT", "DISPLAY", "EC_", "EDGE", "FFFP",
               "FILE_", "FLYOUT", "JOB_", "KF_", "KNOWN", "LIBRARY", "MARKUP", "MERGE", "NATIVE", "Offline",
               "PIDMSI", "PKA", "PLACEHOLDER", "Replaces", "SHELL", "SYNC", "TEAMCOLOR", "VARENUM")
SDK_OR_CRT = {"Vector", "Matrix", "Quaternion", "SpawnpointInfo", "VehicleControls", "VECTOR_2D", "MisnImport",
              "MisnExport", "MisnExport2", "luaL_Reg", "lua_State", "FT", "PMD", "TypeDescriptor",
              "EHExceptionRecord", "stat", "timespec", "ODFName", "HandleInfo"}
# Layout-only sanity checks on SDK types we rely on (asserted against ScriptUtils.h's definitions).
SDK_SANITY = {"Vector", "Matrix", "Quaternion", "SpawnpointInfo", "MisnImport", "MisnExport"}


def tag_of(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def is_project(name: str) -> bool:
    if name.startswith(SKIP_PREFIX):
        return False
    if "<" in name or "::__l" in name:  # templates, function-local types
        return False
    top = name.split("::")[0]
    return top not in SDK_OR_CRT


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="source/missions/shared/vsr_layout_asserts.h")
    args = ap.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    pdb_dir = root / "reference" / "manifest" / "pdb"

    # Merge the four PDBs: identical classes agree; DLL-specific classes come from their own PDB.
    merged: dict[str, dict] = {}
    conflicts = []
    for dll in ("strategy02", "luamission", "instant", "deathmatch01"):
        f = pdb_dir / f"{dll}.types.json"
        if not f.exists():
            continue
        data = json.loads(f.read_text(encoding="utf-8"))
        for name, u in data.items():
            if u["kind"] == "enum":
                continue
            if name in merged:
                a, b = merged[name], u
                if a["size"] != b["size"] or [m["offset"] for m in a["members"]] != [m["offset"] for m in b["members"]]:
                    conflicts.append((name, dll, a["size"], b["size"]))
                continue
            merged[name] = u

    out = [
        "// GENERATED by tools/layout_asserts.py from reference/manifest/pdb/*.types.json - do not edit.",
        "// QA gate 2: every class declared in source/ must have the exact sizeof and member",
        "// offsets GBD's PDBs record. Include at the end of a class header under its guard:",
        "//     #define VSR_LAYOUT_CHECK_<Tag>",
        "//     #include \"vsr_layout_asserts.h\"",
        "// The class befriends struct VsrLayoutCheck_<Tag> (MSVC enforces access in offsetof).",
        "#include <cstddef>",
        "",
        "#define VSR_SIZEOF_IS(T, N) static_assert(sizeof(T) == (N), \"sizeof(\" #T \") != \" #N \" (PDB)\")",
        "#define VSR_OFFSET_IS(T, M, N) static_assert(offsetof(T, M) == (N), \"offsetof(\" #T \", \" #M \") != \" #N \" (PDB)\")",
        "",
    ]
    nclasses = 0
    nasserts = 0
    # group nested types under their outermost class's guard
    for name in sorted(merged):
        if not is_project(name) and name not in SDK_SANITY:
            continue
        u = merged[name]
        top = name.split("::")[0]
        guard = f"VSR_LAYOUT_CHECK_{tag_of(top)}"
        tag = tag_of(name)
        out.append(f"#if defined({guard}) && !defined(VSR_LAYOUT_DONE_{tag})")
        out.append(f"#define VSR_LAYOUT_DONE_{tag}")
        if name in SDK_SANITY and not is_project(name):
            out.append(f"// SDK type (ScriptUtils.h) - sanity check only")
            out.append(f"VSR_SIZEOF_IS({name}, 0x{u['size']:X});")
            nasserts += 1
        else:
            out.append(f"struct VsrLayoutCheck_{tag} {{")
            out.append(f"    static void check() {{")
            out.append(f"        VSR_SIZEOF_IS({name}, 0x{u['size']:X});")
            nasserts += 1
            for m in u["members"]:
                mname = m["name"]
                if not re.match(r"^[A-Za-z_]\w*$", mname):
                    continue
                out.append(f"        VSR_OFFSET_IS({name}, {mname}, 0x{m['offset']:X});")
                nasserts += 1
            out.append("    }")
            out.append("};")
            nclasses += 1
        out.append("#endif")
        out.append("")
    (root / args.out).parent.mkdir(parents=True, exist_ok=True)
    (root / args.out).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{args.out}: {nclasses} classes, {nasserts} asserts")
    for c in conflicts:
        print("CONFLICT between PDBs:", c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
