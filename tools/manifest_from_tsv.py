#!/usr/bin/env python3
"""
manifest_from_tsv.py - per-file / per-function manifest from a decompile's TSV tables.

Reads reference/decompiled/<set>/{all_functions,user_functions,globals}.tsv (the
Ghidra+PDB export) and writes to reference/manifest/<set>/:

    files.tsv       file, functions, min_line, max_line, code_bytes   (project files only)
    functions.tsv   file, min_line, max_line, address, size, name, signature  (sorted by file, line)
    strings.tsv     address, value   (every TerminatedCString in globals.tsv)
    namespaces.txt  user namespaces (copied)
    FILES.md        readable table of files.tsv + totals

The PDB line numbers are the ORIGINAL source lines, so max_line is a lower
bound on each file's length (the last line that produced code). Re-run after
every decompile regeneration (task 8 / task 13).

Usage: python tools/manifest_from_tsv.py [--set strategy02-attempt2]
stdlib only.
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path

csv.field_size_limit(10**9)

PROJECT_PREFIX = "/e:/github/vsr_dll_source/"


def rel(file: str) -> str:
    f = file.replace("\\", "/").lower()
    if f.startswith(PROJECT_PREFIX):
        return f[len(PROJECT_PREFIX):]
    return f


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--set", default="strategy02-attempt2", help="folder under reference/decompiled/")
    args = ap.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    src = root / "reference" / "decompiled" / args.set
    out = root / "reference" / "manifest" / args.set
    out.mkdir(parents=True, exist_ok=True)

    def read(name):
        with open(src / name, encoding="utf-8", newline="") as fh:
            return list(csv.DictReader(fh, delimiter="\t"))

    all_fn = read("all_functions.tsv")
    user_fn = read("user_functions.tsv")
    globs = read("globals.tsv")

    # ---- files.tsv from all_functions (user == Y) : counts, line bounds, bytes
    stats = defaultdict(lambda: {"fn": 0, "min": None, "max": 0, "bytes": 0})
    for r in all_fn:
        if r.get("user") != "Y":
            continue
        f = rel(r["file"])
        s = stats[f]
        s["fn"] += 1
        try:
            lo, hi = int(r["minLine"]), int(r["maxLine"])
        except ValueError:
            lo, hi = None, 0
        if lo is not None:
            s["min"] = lo if s["min"] is None else min(s["min"], lo)
        s["max"] = max(s["max"], hi)
        try:
            s["bytes"] += int(r["size"])
        except ValueError:
            pass
    rows = sorted(stats.items())
    with open(out / "files.tsv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("file\tfunctions\tmin_line\tmax_line\tcode_bytes\n")
        for f, s in rows:
            fh.write(f"{f}\t{s['fn']}\t{s['min'] if s['min'] is not None else ''}\t{s['max']}\t{s['bytes']}\n")

    # ---- functions.tsv from user_functions, sorted by file then line
    def key(r):
        try:
            return (rel(r["file"]), int(r["minLine"]), r["name"])
        except ValueError:
            return (rel(r["file"]), 0, r["name"])
    user_sorted = sorted(user_fn, key=key)
    with open(out / "functions.tsv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("file\tmin_line\tmax_line\taddress\tsize\tname\tsignature\n")
        for r in user_sorted:
            fh.write("\t".join([rel(r["file"]), r["minLine"], r["maxLine"], r["address"], r["size"], r["name"], r["signature"]]) + "\n")

    # ---- strings.tsv
    strs = [(r["address"], r["value"]) for r in globs if r.get("type") == "TerminatedCString"]
    with open(out / "strings.tsv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("address\tvalue\n")
        for a, v in strs:
            fh.write(f"{a}\t{v}\n")

    # ---- namespaces
    ns = src / "user_namespaces.txt"
    if ns.exists():
        (out / "namespaces.txt").write_text(ns.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")

    # ---- FILES.md
    tot_fn = sum(s["fn"] for _, s in rows)
    tot_b = sum(s["bytes"] for _, s in rows)
    nonuser = [r for r in all_fn if r.get("user") != "Y"]
    nonuser_b = sum(int(r["size"]) for r in nonuser if r["size"].isdigit())
    md = [f"# Files — {args.set} (generated by tools/manifest_from_tsv.py)", "",
          f"Source: `reference/decompiled/{args.set}/all_functions.tsv` (Ghidra + PDB export).",
          "`max_line` is the last original source line that produced code: a lower bound on file length.",
          f"Project functions: {tot_fn} ({tot_b:,} bytes of code). Non-project (Lua, STL, CRT): {len(nonuser)} ({nonuser_b:,} bytes).", "",
          "| file | functions | min line | max line | code bytes |", "|---|---:|---:|---:|---:|"]
    for f, s in rows:
        md.append(f"| `{f}` | {s['fn']} | {s['min'] if s['min'] is not None else ''} | {s['max']} | {s['bytes']:,} |")
    md += ["", f"Strings (`TerminatedCString` in globals.tsv): {len(strs)} → `strings.tsv`.",
           f"User functions with signatures: {len(user_fn)} → `functions.tsv`."]
    (out / "FILES.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"{args.set}: {len(rows)} files, {tot_fn} functions, {len(strs)} strings -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
